async function tradePart(resources,step,ctx,selection,planner,query){
  if(!ctx.ledgers.length)clarify('请先上传增持或减持台账。');
  const ids=ctx.ledgers.map(v=>v.id);
  const history=historyFor(ctx.history,'trade');
  const previous=history.filter(s=>s.data.result).at(-1)?.data;
  const originalQuestion=ctx.question??step.question;
  function scoped(plan){
    let filters=[...(plan.filters||[])];
    if(selection){
      const field=fields[selection.field].trade;
      // A bound security is identified across the two raw code columns. Avoid duplicating
      // that same predicate on just one column when the nested planner repeats it.
      if(selection.field==='code')filters=filters.flatMap(f=>{
        if(!bondCodeFields.includes(f.field)||!['eq','in','contains'].includes(f.op))return [f];
        const literal=literalTradeCodeField(originalQuestion,f.field);
        if(literal)return [{...f,field:literal}];
        const values=[].concat(f.value).map(String);
        const same=values.length===selection.names.length&&values.every(x=>selection.names.some(n=>n.toUpperCase()===x.toUpperCase()));
        // The verified upstream set already constrains this step. A model paraphrase
        // cannot narrow it to invented bare aliases, a subset, or another raw column.
        const explicit=values.every(v=>mentionsTradeCode(originalQuestion,v));
        return !same&&explicit?[{...f,field:'券码'}]:[];
      });
      if(!filters.some(f=>f.field===field && f.op==='in' && JSON.stringify(f.value)===JSON.stringify(selection.names)))
        filters.push({field,op:'in',value:selection.names});
    }
    return {...plan,start:step.start||plan.start,end:step.end||plan.end,filters};
  }
  const runQuery=plan=>query(resources,scoped(plan),ids,selection?{verifiedMembers:{field:fields[selection.field].trade,names:selection.names}}:undefined);
  const boundScope=selection?{source:'trade',start:step.start,end:step.end,
    members:{field:fields[selection.field].trade,count:selection.names.length,alreadyApplied:true}}:null;
  const identitySnapshot=ctx.snapshots.find(s=>s.date===ctx.selectedDate)||ctx.snapshots[0];
  const lookupIssuer=identitySnapshot?async alias=>({date:identitySnapshot.date,names:await tradeIssuerCandidates(resources.db,identitySnapshot,alias)}):null;
  const outcome=await planner({question:step.question,originalQuestion,lookupIssuer,boundScope,periodHint:{start:step.start,end:step.end},effort:ctx.effort,apiKey:resources.apiKey,ledgers:ctx.ledgers,
    priorUserQuestions:ctx.history.slice(-8).map(t=>t.question),selectedCodes:selection?.field==='code'?selection.names:[],
    previousPlan:previous?.plan,previousGroups:previous?.result.groups,previousGroupCount:previous?.result.groupCount,
    conversation:history.map(s=>({question:s.question,clarification:s.data.clarification})),runQuery});
  if(outcome.clarification)return {clarification:outcome.clarification};
  const hit=await runQuery(outcome.plan);
  return {plan:hit.plan,result:{...(hit.completeCoverage===undefined?{}:{completeCoverage:hit.completeCoverage}),totals:hit.totals,groups:hit.groups,groupCount:hit.groupCount,warnings:[...(hit.warnings||[]),...(outcome.evidence||[])],highlights:hit.highlights||[]},
    sources:hit.versions.map(tradeSource)};
}
function normalizedFilter(field,value){
  return field==='account'?accountLabel(String(value)):String(value).trim();
}
// Grouping/sorting does not change the population. Ranking, selecting rows or
// unusual predicates do: compare only when the membership predicate is known.
function scopeKey(step){
  const data=step.data,plan=data.plan;
  if(!plan)return null;
  const keys=[];
  const inventoryFields={portfolio:'交易组合',scope:'表内/委外',attribution:'资产端损益还原客户名称'};
  function add(key,value){
    const values=[].concat(value).map(v=>normalizedFilter(key,v)).sort();
    keys.push(JSON.stringify([key,values]));
  }
  if(step.source==='inventory'){
    if(plan.rank || data.roleEvidence?.kind==='unknown' || data.roleEvidence?.kind==='candidate' ||
       data.scopedToPrevious && !step.appliedSelection)return null;
    const local=key=>groupField(key)||inventoryFields[key]||'库存:'+key;
    for(const s of plan.analysis||[]){
      if(s.op==='group'||s.op==='sort')continue;
      if(s.op==='filter' && s.operator==='eq'){add(local(s.field),s.value);continue;}
      return null;
    }
    for(const [field,value] of Object.entries(plan.filters||{}))add(local(field),value);
    if(step.appliedSelection)add(step.appliedSelection.field,step.appliedSelection.names);
  }else{
    for(const f of plan.filters||[]){
      if(!['eq','in'].includes(f.op))return null;
      const field=groupField(f.field)||f.field;
      add(field,f.value);
    }
  }
  return JSON.stringify([...new Set(keys)].sort());
}
export function compareJointSteps(steps,kind){
  if(!['balanceChange','reconcile'].includes(kind))return;
  const [opening,closing,flow]=steps;
  const a=opening?.data,b=closing?.data;
  if(opening?.source!=='inventory'||closing?.source!=='inventory'||!a?.resultId||!b?.resultId||!a.snapshot?.date||!b.snapshot?.date||
    a.snapshot.date>=b.snapshot.date||!Number.isSafeInteger(a.totalCents)||!Number.isSafeInteger(b.totalCents))
    return {kind,note:'需要两个不同日期、按先后排列的余额查询结果才能计算变动。'};
  if(!inventoryPrincipal(a) || !inventoryPrincipal(b))return {kind,note:'计算余额变化需要两期持仓名义本金。'};
  const key=scopeKey(opening);
  if(key===null||key!==scopeKey(closing))return {kind,note:'两期筛选范围或入选名单无法核实一致，已分别列出原结果。'};
  const changeCents=b.totalCents-a.totalCents;
  if(!Number.isSafeInteger(changeCents))return {kind,note:'余额变动金额超出可精确统计范围。'};
  const result={kind,openingCents:a.totalCents,closingCents:b.totalCents,changeCents,note:'持仓变动按期末余额减期初余额计算。'};
  if(kind==='balanceChange')return result;
  const trade=flow?.data,plan=trade?.plan,netCents=trade?.result?.totals.netCents;
  const dayAfter=new Date(Date.parse(a.snapshot.date+'T00:00:00Z')+86400000).toISOString().slice(0,10);
  if(plan && plan.metric!=='net')return {...result,note:'计算差额还需要所选期间的净增持本金。'};
  if(flow?.source!=='trade'||!Number.isSafeInteger(netCents)||plan?.direction!=='both'||plan.start!==dayAfter||plan.end!==b.snapshot.date||
     scopeKey(flow)!==key||!covered(trade.sources,plan.start,plan.end))
    return {...result,note:'两期余额已核实。期间净买入须覆盖期初次日至期末的两侧流水，且筛选范围一致，才能计算差额。'};
  const gapCents=changeCents-netCents;
  if(!Number.isSafeInteger(gapCents))return {...result,note:'差额超出可精确统计范围。'};
  return {...result,netCents,gapCents,note:'差额＝期末余额－期初余额－期间净买入。差额原因需要结合兑付、划转等记录另行核实。'};
}
function covered(sources,start,end){
  for(let year=+start.slice(0,4);year<=+end.slice(0,4);year++){
    const until=end<year+'-12-31'?end:year+'-12-31';
    if(!['buy','sell'].every(dir=>sources?.some(v=>+v.year===year&&v.direction===dir&&v.asOf>=until)))return false;
  }
  return true;
}
function balanceGroups(steps,comparison){
  if(!Number.isSafeInteger(comparison?.changeCents))return;
  const inventory=steps.slice(0,2).map(s=>s.data);
  const dimensions=inventory.map(d=>d.dimensions??[d.plan.group]);
  if(!dimensions[0].length||dimensions[0].includes('none')||JSON.stringify(dimensions[0])!==JSON.stringify(dimensions[1]))return;
  const columns=inventory.map((d,i)=>({id:'balance'+i,label:d.snapshot.date+' 余额'}));
  columns.push({id:'change',label:'期末减期初'});
  const values=new Map();
  for(const [i,d] of inventory.entries()){
    if(d.groupsTruncated||d.groups.reduce((n,g)=>n+g.cents,0)!==d.totalCents)return;
    for(const g of d.groups){
      const key=g.labels?.join(' / ')??g.name;
      if(!values.has(key))values.set(key,[0,0]);
      values.get(key)[i]+=g.cents;
    }
  }
  const rows=[...values].map(([name,[a,b]])=>({name,values:[a,b,b-a]}));
  if(rows.reduce((n,r)=>n+r.values[2],0)!==comparison.changeCents)return;
  const up=rows.filter(r=>r.values[2]>0).length,down=rows.filter(r=>r.values[2]<0).length;
  return {field:dimensions[0].map(k=>analysisFieldLabels[k]??k).join(' / '),columns,rows,
    note:'期末减期初，'+up+' 组增加、'+down+' 组减少、'+(rows.length-up-down)+' 组持平。各组差额合计等于全范围余额变动。'};
}
function alignment(steps){
  if(!steps.some(s=>s.source==='inventory')||!steps.some(s=>s.source==='trade'))return;
  for(const [field,labels] of Object.entries(fields)){
    const byStep=steps.map(s=>table(s,field));
    if(byStep.some(d=>!d?.amount))continue;
    const union=new Map(), columns=[];
    // A ranked selection fixes which rows the question asks to compare, even
    // if one source returned its full population or omitted a selected member.
    const lists=steps.map(s=>s.appliedSelection).filter(list=>list?.field===field);
    for(const list of lists)for(const name of list.names){
      union.set(normalizedFilter(field,name),Array(steps.length).fill(null));
    }
    const restricted=lists.length>0;
    byStep.forEach((group,i)=>{
      const s=steps[i], data=s.data;
      const tradeLabel=s.source==='trade'?[data.plan.start,data.plan.end].filter(Boolean).join(' 至 ')+' '+({buy:'增持',sell:'减持',net:'净增持',gross:'双向合计'})[data.plan.metric]:null;
      columns.push({id:s.id,label:tradeLabel?.trim()||data.snapshot.date+' 余额'});
      for(const [name,cents] of group.pairs){
        if(!name||!Number.isSafeInteger(cents))continue;
        const label=normalizedFilter(field,name);
        if(!union.has(label)){
          if(restricted)continue;
          union.set(label,Array(steps.length).fill(null));
        }
        union.get(label)[i]=cents;
      }
    });
    if(!union.size)continue;
    return {field:labels.label,columns,rows:[...union].slice(0,100).map(([name,values])=>({name,values})),
      note:(restricted?'按入选名单顺序对照。':'按各表返回的'+labels.label+'名称对照。')+'空白表示该名单中未列示。'+(union.size>100?'此处显示前 100 个名称。':'')};
  }
}
async function collectMembers(resources,step,ctx,query){
  if(step.source==='trade'){
    const plan={direction:step.direction,start:step.start,end:step.end,metric:'rows',
      filters:step.filters,groupBy:[step.field==='account'?'会计科目':fields[step.field].trade]};
    const hit=await query(resources,plan,ctx.ledgers.map(v=>v.id),{collectMembers:true});
    const {totals,groups,groupCount,warnings,completeCoverage}=hit;
    return {plan:hit.plan,result:{totals,groups,groupCount,warnings,completeCoverage},sources:hit.versions.map(tradeSource),
      memberNames:completeCoverage?hit.memberNames:undefined};
  }
  const snapshot=ctx.snapshots.find(s=>s.date===step.snapshotDate);
  if(!snapshot)clarify('所选日期没有库存快照。');
  const data=await newInventoryAnswer(resources.db,snapshot,{date:snapshot.date,group:step.field,metric:'count',filters:step.filters},resources.bucket);
  if(!data.resultId||!Array.isArray(data.groups))return data;
  return {...data,memberNames:data.groups.filter(group=>group.count>0).map(group=>group.name)};
}
function compareMembers(steps,field){
  const labels=steps.map(step=>step.question);
  if(steps.some(step=>!Array.isArray(step.data.memberNames)))
    return {field:fields[field].label,labels,note:'部分范围未能核全，无法确认两份完整名单的交集、差集及并集。'};
  const clean=values=>new Set(values.map(v=>normalizedFilter(field,v)).filter(v=>v&&!['（未填）','未填写'].includes(v)));
  const [left,right]=steps.map(step=>clean(step.data.memberNames));
  const both=[],leftOnly=[],rightOnly=[];
  for(const name of left)(right.has(name)?both:leftOnly).push(name);
  for(const name of right)if(!left.has(name))rightOnly.push(name);
  return {field:fields[field].label,dimension:field,labels,both,leftOnly,rightOnly,total:both.length+leftOnly.length+rightOnly.length};
}
export async function executeJointPlan(resources,input,dependencies={}){
  const ctx={history:[],snapshots:[],ledgers:[],...input};
  const prior=ctx.history.at(-1)?.answer?.steps||[];
  const scheduled=new Map(),tasks=[];
  for(const step of ctx.steps){
    const ref=step.operation==='regroup'?step.from:step.selection?.from;
    const linked=typeof ref==='string'&&/^previous\d+$/.test(ref)?prior[Number(ref.slice(8))-1]:scheduled.get(ref);
    const task=(async()=>{
      let selection;
      let data;
      try{
        if(step.selection)selection=/^previous(?:Both|LeftOnly|RightOnly|Union)$/.test(step.selection.from)
          ?previousSetSelection(ctx.history,step.selection):members(await linked,step.selection);
        if(step.operation==='collectMembers'){
          data=await collectMembers(resources,step,ctx,dependencies.tradeQuery||runTradeQuery);
        }else if(step.operation==='calculate'){
          data=await calculateInventory(resources,step,ctx.snapshots);
        }else if(step.operation==='memberSummary'){
          data=await memberSummary(resources,step,ctx,selection);
        }else if(step.operation==='regroup'){
          data=await regroupInventory(resources,step,ctx,await linked);
        }else if(step.source==='portfolio'){
          if(selection)clarify('组合指标只接受明确的账户与分行范围。');
          data=await (dependencies.portfolioMetrics||portfolioMetrics)(resources,{...step.spec,marketPins:ctx.marketPins},ctx.snapshots);
          data={...data,spec:step.spec};
        }else{
          data=step.source==='inventory'?await inventoryPart(resources,step,ctx,selection,dependencies.queryInventory||queryInventory)
            :await tradePart(resources,step,ctx,selection,dependencies.tradePlanner||planFlowQuestion,dependencies.tradeQuery||runTradeQuery);
        }
      }catch(err){
        if(![400,409,422].includes(err?.status))throw err;
        data={clarification:err.message};
      }
      return {id:step.id,source:step.source,question:step.question,data,...(step.source==='portfolio'?{spec:step.spec}:{}),...(selection?{appliedSelection:selection}:{})};
    })();
    scheduled.set(step.id,task);tasks.push(task);
  }
  const steps=await Promise.all(tasks);
  if(ctx.comparison==='memberSets'){
    const memberSets=compareMembers(steps,ctx.steps[0].field);
    for(const step of steps)delete step.data.memberNames;
    return {steps,memberSets};
  }
  explainPortfolioDifferences(steps,prior);
  const comparison=compareJointSteps(steps,ctx.comparison),aligned=balanceGroups(steps,comparison)||alignment(steps);
  return {steps,...(comparison?{comparison}:{}),...(aligned?{alignment:aligned}:{})};
}
