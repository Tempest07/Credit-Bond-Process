async function regroupInventory({db,bucket},step,ctx,source){
  const prior=source?.data;
  const result=prior?.resultId?prior:prior?.overview?.find(item=>item.role==='union')?.result;
  if(source?.source!=='inventory'||!result?.resultId||['unknown','candidate'].includes(result.roleEvidence?.kind))
    clarify('所指库存答案没有可确认的入选持仓，请先确认要分析的持仓范围。');
  const snapshot=ctx.snapshots.find(s=>s.id===result.snapshot?.id);
  if(!snapshot||step.snapshotDate && step.snapshotDate!==snapshot.date)
    clarify('请沿用这批持仓的原快照，或另行指定日期重新查询。');
  let rows=await answerSourceRows(db,result.resultId,snapshot.id);
  if(prior.rankedMembers){
    if(!Object.hasOwn(fields,prior.rankedMembers.field))clarify('当前排名维度不能直接沿用为原表行筛选。');
    const selected=new Set(await matchingRows(db,snapshot,prior.rankedMembers));
    rows=rows.filter(row=>selected.has(row));
  }
  const metric={principal:'principalCents',count:'rowCount',securities:'securityCount'}[step.metric];
  const plan={date:snapshot.date,group:'none',metric:step.metric,filters:{},
    analysis:[{op:'group',fields:step.dimensions,metric}]};
  return newInventoryAnswer(db,snapshot,plan,bucket,
    ['沿用“'+source.question+'”实际入选的 '+rows.length+' 条持仓，按原表行号重新分组。'],undefined,rows);
}
async function inventoryPart(resources,step,ctx,selection,query){
  const history=historyFor(ctx.history,'inventory');
  const previous=history.filter(s=>s.data.resultId).at(-1);
  const date=step.snapshotDate||ctx.selectedDate||previous?.data?.snapshot?.date;
  const snapshot=date?ctx.snapshots.find(s=>s.date===date):ctx.snapshots[0];
  if(!snapshot)clarify(date?'没有 '+date+' 的余额台账。':'请先上传余额台账。');
  const scopeRows=selection?await matchingRows(resources.db,snapshot,selection):undefined;
  const boundScope=selection?{source:'inventory',snapshotDate:snapshot.date,
    members:{field:fields[selection.field].label,count:selection.names.length,alreadyApplied:true}}:null;
  // Limit even a second planner/evidence request to the exact pinned version.
  const samePeriod=previous?.data?.snapshot?.id===snapshot.id;
  return query({question:step.question,effort:ctx.effort,snapshotId:snapshot.id,
    ...(samePeriod && !selection?{previousResultId:previous.data.resultId}:{}),
    conversation:inventoryTurns(history)},'ask',resources,snapshot,{snapshots:[snapshot],scopeRows,boundScope});
}
