export async function executeJointPlan(resources,input,dependencies={}){
  const ctx={history:[],snapshots:[],ledgers:[],...input};
  const prior=ctx.history.at(-1)?.answer?.steps||[];
  const scheduled=new Map(),tasks=[];
  for(const step of ctx.steps){
    const ref=step.operation==='regroup'?step.from:step.selection?.from;
    const old=typeof ref==='string'&&/^earlier([2-8])step([1-5])$/.exec(ref);
    const linked=old?ctx.history.at(-Number(old[1]))?.answer?.steps[Number(old[2])-1]:
      typeof ref==='string'&&/^previous\d+$/.test(ref)?prior[Number(ref.slice(8))-1]:scheduled.get(ref);
    const task=(async()=>{
      let selection;
      let data;
      try{
        if(step.selection)selection=/^previous(?:Both|LeftOnly|RightOnly|Union)$/.test(step.selection.from)
          ?previousSetSelection(ctx.history,step.selection):members(await linked,step.selection,ctx.question||step.question);
        if(step.operation==='tradeDateBridge'){
          data=await tradeDateBridge(resources,step.start,step.end,step.filters,ctx.ledgers.map(v=>v.id));
        }else if(step.operation==='flowMatrix'){
          data=await tradeMatrix(resources,step,ctx,dependencies.tradeQuery||runTradeQuery);
        }else if(step.operation==='collectMembers'){
          data=await collectMembers(resources,step,ctx,dependencies.tradeQuery||runTradeQuery);
        }else if(step.operation==='profile'){
          data=await inventoryProfile(resources,step,ctx);
        }else if(step.operation==='memberAnalysis'){
          data=await memberAnalysis(resources,step,ctx);
        }else if(step.operation==='calculate'){
          data=await calculateInventory(resources,step,ctx.snapshots);
        }else if(step.operation==='snapshotEvidence'){
          data=await snapshotEvidence(resources,step,ctx);
        }else if(step.operation==='memberShares'){
          data=await memberShares(resources,step,ctx,selection,await linked);
        }else if(step.operation==='holdingRows'){
          data=await describeHoldingRows(resources.db,await memberSummary(resources,step,ctx,selection));
        }else if(step.operation==='memberSummary'){
          data=await memberSummary(resources,step,ctx,selection);
        }else if(step.operation==='regroup'){
          data=await regroupInventory(resources,step,ctx,await linked);
        }else if(step.source==='portfolio'){
          if(selection)clarify('组合指标只接受明确的账户与分行范围。');
          data=await (dependencies.portfolioMetrics||portfolioMetrics)(resources,{...step.spec,marketPins:ctx.marketPins},ctx.snapshots);
          data={...data,spec:step.spec};
        }else{
          data=step.source==='inventory'?await inventoryPart(resources,step,ctx,selection,dependencies.queryInventory||queryInventory)
            :await tradePart(resources,step,ctx,selection,dependencies.tradePlanner||planFlowQuestion,dependencies.tradeQuery||runTradeQuery);
        }
      }catch(err){
        if(![400,409,422].includes(err?.status))throw err;
        data={clarification:err.message};
      }
      return {id:step.id,source:step.source,question:step.question,data,...(step.source==='portfolio'?{spec:step.spec}:{}),...(selection?{appliedSelection:selection}:{})};
    })();
    scheduled.set(step.id,task);tasks.push(task);
  }
  const steps=await Promise.all(tasks);
  if(ctx.comparison==='memberSets'){
    const memberSets=compareMembers(steps,ctx.steps[0].field);
    const ledgerReport=tradeSetReport(steps,memberSets);
    for(const step of steps){delete step.data.memberNames;delete step.data.memberAmounts;}
    return {steps,memberSets,...(ledgerReport?{ledgerReport}:{})};
  }
  explainPortfolioDifferences(steps,prior);
  const comparison=compareJointSteps(steps,ctx.comparison),aligned=balanceGroups(steps,comparison)||alignment(steps);
  const priorReport=Number.isSafeInteger(comparison?.gapCents)?null:previousReconciliation(ctx,steps);
  const reportStep=steps.find(s=>s.data.ledgerReport);
  const cohortShare=await selectedScopeShare(resources.db,steps,ctx.question);
  const ledgerReport=cohortShare||reportStep?.data.ledgerReport||reconciliationReport(steps,comparison)||priorReport||partialBalanceReport(steps)||selectedTradePeriods(steps,ctx);
  if(reportStep)delete reportStep.data.ledgerReport;
  return {steps,...(comparison&&!priorReport?{comparison}:{}),...(aligned?{alignment:aligned}:{}),...(ledgerReport?{ledgerReport}:{})};
}
